/* Rewrite the import map in index.html so a version bump busts every module.
 *
 * WHY THIS EXISTS. `index.html` loads `js/main.js?v=X`, and main.js imports
 * thirty other modules with no query on any of them. Bumping the version
 * therefore busts exactly one file, and a device ends up running new markup and
 * new main.js against whichever copy of everything else the browser felt like
 * keeping. Observed on 2026-08-21 — the header read v0.19.0 while v0.20.0 was
 * on disk — and again on 2026-08-25, when a version bump to 0.21.0 left the
 * header reading 0.20.2 on a page that had just been reloaded.
 *
 * The app has always DETECTED this and shouted about it (see the stale-build
 * check at the end of `js/main.js`), which is much better than nothing and
 * still leaves the operator with a device they cannot use. This is the fix the
 * comment there asks for, minus the build step: an import map is one place, in
 * the markup, that rewrites every module specifier to a versioned URL. The
 * browser then treats a new version as thirty new URLs, because it is.
 *
 * Keys are relative, so the map keeps working under a deployment sub-path such
 * as GitHub Pages: an import map key that looks like a URL is resolved against
 * the document's base URL, and so is the `./coverage.js` inside a module, so
 * the two meet at the same absolute URL wherever the app is served from.
 *
 * Run after changing VERSION:
 *
 *     node tools/build-importmap.mjs
 *
 * `tests/import-map.test.mjs` fails if it has not been run, so this cannot be
 * forgotten quietly — which is the only failure mode that matters here.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const BEGIN = '<!-- BEGIN generated import map -->';
export const END = '<!-- END generated import map -->';

/** Every module the map must cover, in a stable order. */
export function moduleFiles(dir = join(root, 'js')) {
  return readdirSync(dir).filter(f => f.endsWith('.js')).sort();
}

/** The version the markup should be stamped with. */
export function currentVersion(dir = root) {
  const src = readFileSync(join(dir, 'js', 'version.js'), 'utf8');
  const m = src.match(/export const VERSION = '([^']+)'/);
  if (!m) throw new Error('js/version.js does not declare VERSION');
  return m[1];
}

export function renderImportMap(version, files) {
  const imports = files.map(f => `    "./js/${f}": "./js/${f}?v=${version}"`).join(',\n');
  return [
    BEGIN,
    '<!-- Generated by tools/build-importmap.mjs. Do not hand-edit: run the tool',
    '     after bumping VERSION in js/version.js. Every module carries the query',
    '     so a version bump busts the whole graph rather than only main.js. -->',
    '<script type="importmap">',
    '{',
    '  "imports": {',
    imports,
    '  }',
    '}',
    '</script>',
    END
  ].join('\n');
}

/**
 * Stamp the version onto the two URLs the import map cannot reach.
 *
 * MEASURED, 2026-09-23, while checking that a bump to 0.30.0 had landed. It had
 * not. The page still ran 0.29.0.
 *
 * The map rewrites module specifiers, and `js/main.js?v=0.29.0` in the entry
 * `<script>` tag is not the specifier `./js/main.js` — it is already a
 * different URL, so the map never applies to it. The entry point and the
 * stylesheet therefore kept whatever version they were last hand-edited to,
 * while all thirty modules behind them moved. The device runs the new graph
 * through the old front door, which is the exact failure this tool was written
 * to end, surviving inside the tool itself.
 *
 * The stale-build check in main.js still catches the symptom. This removes the
 * cause.
 */
export function stampEntryPoints(html, version) {
  // Only our own files. A cache-busting query on a third-party URL is at best
  // useless and at worst a cache miss someone else pays for.
  const ours = src => !/^[a-z]+:|^\/\//i.test(src);
  return html
    .replace(/(<script\b[^>]*\bsrc=")([^"?]+)(?:\?v=[^"]*)?(")/g,
      (whole, a, src, b) => (ours(src) ? `${a}${src}?v=${version}${b}` : whole))
    .replace(/(<link\b[^>]*\bhref=")([^"?]+\.css)(?:\?v=[^"]*)?(")/g,
      (whole, a, href, b) => (ours(href) ? `${a}${href}?v=${version}${b}` : whole));
}

/** Replace the block in index.html, or insert it just before </head>. */
export function applyTo(html, block) {
  const start = html.indexOf(BEGIN);
  const end = html.indexOf(END);
  if (start >= 0 && end > start) {
    return html.slice(0, start) + block + html.slice(end + END.length);
  }
  const head = html.indexOf('</head>');
  if (head < 0) throw new Error('index.html has no </head>');
  return html.slice(0, head) + block + '\n' + html.slice(head);
}

if (import.meta.url === `file://${process.argv[1]}`.replace(/\\/g, '/')
    || process.argv[1]?.endsWith('build-importmap.mjs')) {
  const version = currentVersion();
  const files = moduleFiles();
  const page = join(root, 'index.html');
  const html = readFileSync(page, 'utf8');
  const next = stampEntryPoints(applyTo(html, renderImportMap(version, files)), version);
  writeFileSync(page, next, 'utf8');
  console.log(`import map rewritten: ${files.length} modules at v${version}, `
    + 'entry script and stylesheet stamped to match');
}
